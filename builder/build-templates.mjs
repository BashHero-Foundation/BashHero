import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { createHash } from "node:crypto";

const BUILDER_DIR = process.argv[2] ?? "builder";
const TEMPLATES = join(BUILDER_DIR, "templates");
const OUT = join(BUILDER_DIR, "templates.bundle.js");

const templates = {};

for (const entry of await readdir(TEMPLATES, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue;
  const dir = join(TEMPLATES, entry.name);
  const files = {};
  for (const f of await readdir(dir)) {
    if (!f.endsWith(".json")) continue;
    files[f] = JSON.parse(await readFile(join(dir, f), "utf8"));
  }
  templates[entry.name] = files;
}

const version = createHash("sha256")
  .update(JSON.stringify(templates))
  .digest("hex")
  .slice(0, 12);

const payload =
  `// Auto-generated by builder/build-templates.mjs — do not edit.\n` +
  `window.__TEMPLATES_VERSION__ = ${JSON.stringify(version)};\n` +
  `window.__TEMPLATES__ = ${JSON.stringify(templates, null, 2)};\n`;

await writeFile(OUT, payload, "utf8");
console.log(
  `Wrote ${OUT} (${Object.keys(templates).length} template(s), ` +
  `${Object.values(templates).reduce((n, f) => n + Object.keys(f).length, 0)} file(s), v${version})`
);